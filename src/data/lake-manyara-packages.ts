import { getPackagePrice } from "@/data/tarangire-packages";
import { packageSchema } from "@/types/package";
import {
  packagePricingSchema,
  type PackageGroupSize,
  type PackageMonth,
  type PackageSeason,
  type PackageTier,
} from "@/types/tarangire-package";
import { z } from "zod";

const activitySchema = z.object({
  time: z.string().min(1),
  text: z.string().min(1),
});

const itineraryDaySchema = z.object({
  day: z.number().int().positive(),
  title: z.string().min(1),
  label: z.string().min(1),
  story: z.string().min(1),
  activities: z.array(activitySchema).min(1),
  meals: z.array(z.enum(["Breakfast", "Lunch", "Dinner"])),
  overnight: z.string().min(1),
});

const lakeManyaraPackageSchema = packageSchema.extend({
  name: z.string().min(1),
  duration: z.string().min(1),
  nights: z.number().int().nonnegative(),
  tagline: z.string().min(1),
  hook: z.string().min(1),
  pace: z.string().min(1),
  accommodationSummary: z.string().min(1),
  itinerary: z.array(itineraryDaySchema).min(1),
  pricing: packagePricingSchema,
  faqs: z.array(z.object({
    question: z.string().min(1),
    answer: z.string().min(1),
  })).min(3),
  seo: z.object({
    title: z.string().min(1).max(60),
    description: z.string().min(1).max(155),
    keywords: z.array(z.string().min(1)).min(1),
  }),
  seasonsNote: z.string().min(1),
  heroImage: z.string().startsWith("/images/lake-manyara/"),
  heroAlt: z.string().min(1),
  cardImage: z.string().startsWith("/images/packages/lake-manyara/"),
  cardAlt: z.string().min(1),
  gallery: z.array(z.object({
    src: z.string().startsWith("/images/packages/lake-manyara/"),
    alt: z.string().min(1),
    span: z.enum(["wide", "tall", "square"]).optional(),
  })).length(6),
  routeStops: z.array(z.string().min(1)),
}).refine((item) => item.itinerary.length === item.days, {
  message: "Itinerary must include one entry for each package day.",
});

export type LakeManyaraPackage = z.infer<typeof lakeManyaraPackageSchema>;

